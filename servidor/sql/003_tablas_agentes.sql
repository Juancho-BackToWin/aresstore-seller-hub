-- Tablas creadas el 26-nov-2026 para los agentes, ya aplicadas en
-- gestion-arestora. Se versionan aquí para que el esquema del repositorio
-- coincida con el de producción (leído de information_schema el 27-nov).
-- Las tres con RLS activo y SIN políticas: solo las lee el servidor.

-- Configuración del servidor (p. ej. recolector_key). Nunca un secreto de Amazon:
-- esos viven en los secretos de funciones de Supabase.
create table if not exists public.amz_config (
  clave       text primary key,
  valor       text not null,
  actualizado timestamptz not null default now()
);
alter table public.amz_config enable row level security;

-- Líneas de pedido de la Orders API (amz-recolector). Sin datos del comprador.
-- Incluye pedidos pendientes y cancelados: filtrar por estado. precio es el
-- importe con IVA de la línea; no es dinero cobrado.
create table if not exists public.amz_pedidos_api (
  order_id             text not null,
  order_item_id        text not null,
  fecha_compra         timestamptz,
  ultima_actualizacion timestamptz,
  estado               text,
  canal                text,
  marketplace_id       text,
  pais                 text,
  sku                  text,
  asin                 text,
  unidades             integer,
  unidades_enviadas    integer,
  precio               numeric,
  iva                  numeric,
  descuento            numeric,
  divisa               text,
  b2b                  boolean,
  recogido             timestamptz not null default now(),
  primary key (order_id, order_item_id)
);
alter table public.amz_pedidos_api enable row level security;

-- Manual de jugadas del Agente Investigador.
create table if not exists public.amz_playbook (
  id          bigint generated by default as identity primary key,
  situacion   text not null,
  senal       text not null,
  accion      text not null,
  limites     text,
  evidencia   text not null check (evidencia in ('consenso','opinion_experto','en_debate')),
  fuentes     jsonb not null default '[]'::jsonb,
  aplica_a    text default 'ES',
  vigente     boolean not null default true,
  actualizado timestamptz not null default now()
);
alter table public.amz_playbook enable row level security;

revoke all on public.amz_config, public.amz_pedidos_api, public.amz_playbook from anon, authenticated;
